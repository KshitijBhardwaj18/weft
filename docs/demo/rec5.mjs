import * as fs from "node:fs";
import { chromium } from "playwright";
const BASE = "http://localhost:3200";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: "/tmp/demo-rec/out5", size: { width: 1440, height: 900 } } });
await ctx.addCookies([{ name: "weft_session", value: "demo", url: BASE }, { name: "weft_as", value: "kshitij", url: BASE }]);
const page = await ctx.newPage();
const T0 = Date.now(); const beats = [];
const beat = (title, body) => beats.push({ t: (Date.now() - T0) / 1000, title, body });
const settle = async () => { await page.waitForLoadState("domcontentloaded"); await page.waitForTimeout(1200); };
const box = () => page.locator("main form input, main form textarea").last();
async function say(text) { await box().click(); await box().type(text, { delay: 28 }); await page.keyboard.press("Enter"); }

await page.goto(BASE + "/supplier/sri"); await settle();
beat("Talk where the work happens", "Suppliers, the team and the AI teammates share one set of conversations, and every message is part of the plan.");
await page.waitForTimeout(2500);
beat("A supplier writes, the plan updates", "Murugan types an update the way he always would. Shuttle reads it and moves the order forward on its own, quoting the message.");
await say("Cutting done for the olive leggings PO-017");
await page.waitForFunction(() => /Stitching/.test(document.body.innerText), null, { timeout: 90000 }).catch(() => {});
await page.waitForTimeout(4000);
await page.goto(BASE + "/production"); await settle();
beat("No one retyped anything", "PO-017 is already in Stitching on the production board, linked back to Murugan's message.");
await page.waitForTimeout(4500);
await page.goto(BASE + "/chat/agent-shuttle"); await settle();
beat("Chat with a teammate", "Ask Shuttle anything about production. It answers from the live plan, and See why shows how.");
await say("Which factory orders could still put the Black Drop at risk?");
await page.waitForSelector("text=/See why · \\d+ quer/", { timeout: 120000 }).catch(() => {});
await page.waitForTimeout(1500);
await page.locator("text=/See why · \\d+ quer/").last().click().catch(() => {});
await page.waitForTimeout(6000);
await page.goto(BASE + "/chat/team-ops"); await settle();
beat("Mention a teammate in any thread", "In #ops, the team tags @weft and gets an answer in place, without leaving the conversation.");
await say("@weft what do we need from suppliers this week?");
await page.waitForFunction(() => document.querySelectorAll("button").length && /See why · \d+ quer/.test(document.body.innerText), null, { timeout: 120000 }).catch(() => {});
await page.waitForTimeout(6000);
beats.push({ t: (Date.now() - T0) / 1000, end: true });
const v = page.video(); await ctx.close(); await b.close();
fs.writeFileSync("/tmp/demo-rec/beats5.json", JSON.stringify(beats, null, 1));
console.log("VIDEO", await v.path());
